#!/usr/bin/env node
const fs = require('fs');
const path = require('path');

const repoRoot = path.resolve(__dirname, '..');
const backendSrc = path.join(repoRoot, 'backend', 'src');

function walk(dir, files = []) {
  const items = fs.readdirSync(dir, { withFileTypes: true });
  for (const it of items) {
    const p = path.join(dir, it.name);
    if (it.isDirectory()) walk(p, files);
    else files.push(p);
  }
  return files;
}

function extractSwaggerPaths(fileContent) {
  const lines = fileContent.split(/\r?\n/);
  const results = [];
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    const m = line.match(/\*\s*(\/[^:]+):/);
    if (m) {
      const pathLine = m[1].trim();
      // look ahead for verb lines (get, post, put, delete, patch)
      const verbs = [];
      for (let j = i + 1; j < Math.min(i + 30, lines.length); j++) {
        const vm = lines[j].match(/\*\s*(get|post|put|delete|patch):/i);
        if (vm) verbs.push(vm[1].toLowerCase());
        if (lines[j].includes('responses:')) break;
      }
      if (verbs.length === 0) verbs.push('get'); // fallback
      results.push({ path: pathLine, verbs });
    }
  }
  return results;
}

function toFilename(p, verb) {
  // remove leading slash
  let s = p.replace(/^\//, '');
  // replace {param} with param
  s = s.replace(/\{(.*?)\}/g, '$1');
  // replace / with .
  s = s.replace(/[\/]+/g, '.');
  if (!s) s = 'index';
  return `${s}.${verb}.ts`;
}

const allFiles = walk(backendSrc).filter(f => f.endsWith('.ts'));
const controllers = allFiles.filter(f => f.includes('/api/') && f.endsWith('Controller.ts'));

const features = {};
for (const ctrl of controllers) {
  const rel = path.relative(backendSrc, ctrl);
  const content = fs.readFileSync(ctrl, 'utf8');
  const items = extractSwaggerPaths(content);
  if (items.length === 0) continue;
  // derive feature name from path: src/features/<feature>/*
  const parts = rel.split(path.sep);
  const featIdx = parts.indexOf('features');
  let featureName = parts[featIdx + 1] || 'unknown';
  if (!features[featureName]) features[featureName] = [];
  features[featureName].push({ controller: rel, endpoints: items.map(it => ({ path: it.path, verbs: it.verbs, files: it.verbs.map(v => toFilename(it.path, v)) })) });
}

// generate markdown
let md = '\n### Auto-generated per-feature checklist (generated)\n\n';
md += 'The following checklist was generated by scanning controller files for `@swagger` blocks. Each operation lists suggested per-op filenames (follow the project naming convention).\n\n';
for (const [feature, ctrls] of Object.entries(features).sort()) {
  md += `#### Feature: **${feature}**\n\n`;
  for (const c of ctrls) {
      md += '- **Controller:** `' + '/' + c.controller + '`\n';
      for (const ep of c.endpoints) {
        md += '  - Path: `' + ep.path + '` — Verbs: ' + ep.verbs.join(', ') + '\n';
        md += '    - Suggested files:\n';
        for (const f of ep.files) md += '      - [ ] `' + 'paths/' + f + '`\n';
      }
  }
  md += '\n';
}

// write to stdout for now
console.log(md);

// also write to a temporary file
fs.writeFileSync(path.join(repoRoot, 'tmp', 'swagger-checklist.md'), md, 'utf8');
